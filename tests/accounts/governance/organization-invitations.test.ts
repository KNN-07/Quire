import { expect, test } from "bun:test";
import { z } from "zod";
import { InvitationSchema, MembershipSchema } from "@quire/contracts";
import { fixtureIds as ids } from "../../fixtures/foundation";
import { data, governanceFixture } from "./harness";

test("organization invitations persist pending until the verified recipient explicitly accepts", async () => {
  await using app = await governanceFixture();
  const admin = await app.login();
  const recipient = await app.login("sam@quire.local");
  const outsider = await app.login("outsider@quire.local");
  const path = `/api/organizations/${ids.team}/invitations`;
  const created = await admin.write(path, { email: "sam@quire.local", role: "manager", expectedVersion: 0 }, { key: "org-invite-create" });
  expect(created.status).toBe(200);
  const invitation = await data(created, InvitationSchema);
  expect(invitation.status).toBe("pending");
  expect(invitation.organizationId).toBe(ids.team);
  expect(await app.runtime.db.get("SELECT id FROM members WHERE organization_id=? AND user_id=?", [ids.team, ids.sam])).toBeNull();
  const list = await data(await admin.get(path), z.object({ items: z.array(InvitationSchema) }));
  expect(list.items.map(item => item.id)).toContain(invitation.id);
  const recipientPath = `/api/organization-invitations/${invitation.id}`;
  expect((await outsider.get(recipientPath)).status).toBe(403);
  const preview = await recipient.get(recipientPath);
  expect(preview.status).toBe(200);
  expect(preview.headers.get("cache-control")).toBe("private, no-store");
  expect(await preview.json()).toMatchObject({ data: { invitation: { id: invitation.id }, organizationName: "Robotics Lab" } });
  const firstMail = z.object({ body: z.string() }).parse(await app.runtime.db.get("SELECT body FROM mail_outbox WHERE dedupe_key=?", [`organization-invite:${invitation.id}:0`]));
  const oldToken = new URL(firstMail.body).searchParams.get("token");
  const resent = await data(await admin.write(`${path}/${invitation.id}/resend`, { expectedVersion: 0 }), InvitationSchema);
  expect(resent.version).toBe(1);
  const latestMail = z.object({ body: z.string() }).parse(await app.runtime.db.get("SELECT body FROM mail_outbox WHERE dedupe_key=?", [`organization-invite:${invitation.id}:1`]));
  const token = new URL(latestMail.body).searchParams.get("token");
  expect(token).not.toBe(oldToken);
  expect((await recipient.write(`${recipientPath}/accept`, { token: oldToken, expectedVersion: 1 })).status).toBe(403);
  expect((await outsider.write(`${recipientPath}/accept`, { token, expectedVersion: 1 })).status).toBe(403);
  expect((await recipient.write(`${recipientPath}/accept`, { token, expectedVersion: 0 })).status).toBe(409);
  const member = await data(await recipient.write(`${recipientPath}/accept`, { token, expectedVersion: 1 }, { key: "org-invite-accept" }), MembershipSchema);
  expect(member).toMatchObject({ organizationId: ids.team, userId: ids.sam, role: "manager", licensed: false });
  const replay = await data(await recipient.write(`${recipientPath}/accept`, { token, expectedVersion: 1 }, { key: "org-invite-accept" }), MembershipSchema);
  expect(replay.id).toBe(member.id);
  expect((await recipient.write(`${recipientPath}/accept`, { token, expectedVersion: 1 })).status).toBe(409);
  expect(await app.runtime.db.get("SELECT status,version FROM invitations WHERE id=?", [invitation.id])).toMatchObject({ status: "accepted", version: 2 });
});

test("organization invitation authority, revocation, expiry and existing membership stay enforced", async () => {
  await using app = await governanceFixture();
  let admin = await app.login();
  const outsider = await app.login("outsider@quire.local");
  let recipient = await app.login("sam@quire.local");
  const path = `/api/organizations/${ids.team}/invitations`;
  expect((await outsider.write(path, { email: "sam@quire.local", role: "member", expectedVersion: 0 })).status).toBe(403);
  const invitation = await data(await admin.write(path, { email: "sam@quire.local", role: "member", expectedVersion: 0 }), InvitationSchema);
  expect((await admin.write(path, { email: "SAM@quire.local", role: "member", expectedVersion: 1 })).status).toBe(409);
  const mail = z.object({ body: z.string() }).parse(await app.runtime.db.get("SELECT body FROM mail_outbox WHERE dedupe_key=?", [`organization-invite:${invitation.id}:0`]));
  const token = new URL(mail.body).searchParams.get("token");
  app.setTime("2026-11-03T12:00:00.000Z");
  admin = await app.login();
  recipient = await app.login("sam@quire.local");
  expect((await recipient.write(`/api/organization-invitations/${invitation.id}/accept`, { token, expectedVersion: 0 })).status).toBe(403);
  expect((await admin.write(`${path}/${invitation.id}`, { expectedVersion: 0 }, { method: "DELETE" })).status).toBe(200);
  expect((await admin.write(`${path}/${invitation.id}/resend`, { expectedVersion: 1 })).status).toBe(409);
  expect(await app.runtime.db.get("SELECT id FROM members WHERE organization_id=? AND user_id=?", [ids.team, ids.sam])).toBeNull();
  expect((await admin.write(path, { email: "kien@quire.local", role: "member", expectedVersion: 1 })).status).toBe(409);
});

test("managers invite only ordinary members and accepting cannot overwrite a newer membership", async () => {
  await using app = await governanceFixture();
  const admin = await app.login();
  const manager = await app.login("mai@quire.local");
  const recipient = await app.login("sam@quire.local");
  const members = `/api/organizations/${ids.team}/members`;
  const path = `/api/organizations/${ids.team}/invitations`;
  expect((await admin.write(members, { userId: ids.mai, role: "manager", licensed: false, expectedVersion: 0 })).status).toBe(200);
  expect((await manager.write(path, { email: "new-member@example.test", role: "manager", expectedVersion: 1 })).status).toBe(403);
  const body = { email: "new-member@example.test", role: "member", expectedVersion: 1 };
  const created = await data(await manager.write(path, body, { key: "manager-invite" }), InvitationSchema);
  const replay = await data(await manager.write(path, body, { key: "manager-invite" }), InvitationSchema);
  expect(replay.id).toBe(created.id);
  expect(await app.runtime.db.get("SELECT id FROM users WHERE primary_email=?", [body.email])).toBeNull();
  expect(await app.runtime.db.get("SELECT count(*) AS total FROM mail_outbox WHERE dedupe_key=?", [`organization-invite:${created.id}:0`])).toMatchObject({ total: 1 });
  const pending = await data(await admin.write(path, { email: "sam@quire.local", role: "member", expectedVersion: 2 }), InvitationSchema);
  expect((await admin.write(members, { userId: ids.sam, role: "admin", licensed: false, expectedVersion: 3 })).status).toBe(200);
  const mail = z.object({ body: z.string() }).parse(await app.runtime.db.get("SELECT body FROM mail_outbox WHERE dedupe_key=?", [`organization-invite:${pending.id}:0`]));
  const token = new URL(mail.body).searchParams.get("token");
  expect((await recipient.write(`/api/organization-invitations/${pending.id}/accept`, { token, expectedVersion: 0 })).status).toBe(409);
  expect(await app.runtime.db.get("SELECT role FROM members WHERE organization_id=? AND user_id=?", [ids.team, ids.sam])).toMatchObject({ role: "admin" });
});
