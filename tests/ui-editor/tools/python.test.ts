import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { fileURLToPath } from "node:url";
import { endpoints, resultSchema } from "@quire/contracts";
import { fixtureIds } from "../../fixtures/foundation";
import { editorValue } from "../../../apps/web/src/features/editor/shared";
import { authenticatedContext, startEditorApplication, startEditorBrowser, waitForRenderedText } from "../shared";
import type { EditorApplication, EditorBrowser } from "../shared";
import { createInputFile, disposePage, mount, responseAfter, toolScenario } from "./helpers";

describe("installed opt-in browser Python", () => {
  const resources = new AsyncDisposableStack();
  let app: EditorApplication;
  let browser: EditorBrowser;
  beforeAll(async () => {
    try {
      app = resources.use(await startEditorApplication());
      console.info("TOOLS_PYTHON_OWNED", { api: app.apiUrl.origin, web: app.url.origin, root: app.dataDir });
      browser = resources.use(await startEditorBrowser());
    } catch (error) { await resources.disposeAsync(); throw error; }
  }, 120_000);
  afterAll(async () => {
    await resources.disposeAsync();
    console.info("TOOLS_PYTHON_CLOSED", { api: app.apiUrl.origin, web: app.url.origin, root: app.dataDir });
  }, 30_000);
  test("executes installed Python and writes only approved generated bytes while denying Viewer saves", () => toolScenario(async () => {
    // Given the real runtime installation, native project, and a script saved through the API.
    await using owner = await authenticatedContext(browser, app, { viewport: { width: 1440, height: 900 } });
    const expected = "Approved generated output 😀\n";
    const script = await createInputFile(owner, { projectId: fixtureIds.project, origin: app.url.origin,
      path: "generate-proof.py", text: `from pathlib import Path\nPath("/outputs/result.txt").write_text(${JSON.stringify(expected)}, encoding="utf-8")\nprint("Produced result.txt")\n` });
    const page = await owner.context.newPage();
    await mount(page, fixtureIds.project);
    await page.getByLabel("Editor tool", { exact: true }).selectOption("python");
    const directory = process.env["QUIRE_TEST_PYODIDE_URL"] ?? "/extensions/pyodide/";
    const version = process.env["QUIRE_TEST_PYODIDE_VERSION"] ?? "314.0.7";
    await page.getByLabel("Installed runtime directory", { exact: true }).fill(new URL(directory, app.url).href);
    await page.getByLabel("Pinned Pyodide version", { exact: true }).fill(version);
    await page.getByLabel("Enable browser Python on this browser", { exact: true }).check();
    await page.getByRole("button", { name: "Save installation configuration", exact: true }).click();
    await waitForRenderedText(page, "Browser installation configuration saved.");
    await page.getByLabel("Project Python script", { exact: true }).selectOption(script.id);
    const externalOrigins: string[] = [];
    page.on("request", request => {
      const url = new URL(request.url());
      if (/^https?:$/.test(url.protocol) && url.origin !== app.url.origin) externalOrigins.push(url.origin);
    });
    // When the actual installed runtime executes without approving an output yet.
    await page.getByRole("button", { name: "Run selected Python", exact: true }).click();
    await waitForRenderedText(page, "Generated file review");
    const beforeResponse = await owner.context.request.get(`/api/projects/${fixtureIds.project}/files`, { params: { branch: "main" } });
    const before = editorValue(resultSchema(endpoints.filesList.output).parse(await beforeResponse.json()));
    expect(before.some(file => file.path === "result.txt")).toBe(false);
    await page.getByLabel("Project path for result.txt", { exact: true }).fill("approved-output.txt");
    await page.getByRole("checkbox", { name: /Approve result\.txt/ }).check();
    const savedResponse = await responseAfter(page, { path: `/api/projects/${fixtureIds.project}/uploads`, method: "POST" }, () =>
      page.getByRole("button", { name: "Save approved files", exact: true }).click());
    const saved = editorValue(resultSchema(endpoints.filesUpload.output).parse(await savedResponse.json()))[0];
    if (!saved) throw new TypeError("Approval did not return an actual persisted file");
    const bytes = await owner.context.request.get(`/api/projects/${fixtureIds.project}/files/${saved.id}/content`, { params: { branch: "main" } });
    // Then exact generated bytes are persisted only after approval.
    expect(new Uint8Array(await bytes.body())).toEqual(new TextEncoder().encode(expected));
    expect(saved.path).toBe("approved-output.txt");
    expect(externalOrigins).toEqual([]);
    await waitForRenderedText(page, "Approved generated files saved");
    await page.screenshot({ path: fileURLToPath(new URL("./evidence/python-approved-1440-light.png", import.meta.url)), fullPage: true });
    await disposePage(page);
    await using viewer = await authenticatedContext(browser, app, { email: "alex@quire.local", viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 3 });
    const reader = await viewer.context.newPage();
    await mount(reader, fixtureIds.project);
    await reader.getByLabel("Editor tool", { exact: true }).selectOption("python");
    await reader.getByLabel("Installed runtime directory", { exact: true }).fill(new URL(directory, app.url).href);
    await reader.getByLabel("Pinned Pyodide version", { exact: true }).fill(version);
    await reader.getByLabel("Enable browser Python on this browser", { exact: true }).check();
    await reader.getByLabel("Project Python script", { exact: true }).selectOption(script.id);
    await reader.getByRole("button", { name: "Run selected Python", exact: true }).click();
    await waitForRenderedText(reader, "Generated file review");
    await reader.getByRole("checkbox", { name: /Approve result\.txt/ }).check();
    expect(await reader.getByRole("button", { name: "Save approved files", exact: true }).isDisabled()).toBe(true);
    await reader.screenshot({ path: fileURLToPath(new URL("./evidence/python-review-390-light.png", import.meta.url)), fullPage: true });
    await reader.emulateMedia({ colorScheme: "dark" });
    await reader.screenshot({ path: fileURLToPath(new URL("./evidence/python-review-390-dark.png", import.meta.url)), fullPage: true });
    await reader.getByRole("button", { name: "Discard generated files", exact: true }).click();
    await disposePage(reader);
  }), 120_000);
});
